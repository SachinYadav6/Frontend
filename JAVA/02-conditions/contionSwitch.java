public class contionSwitch {
public static void main(String[] args) {
    String fruit = "orange";
   switch (fruit) {
        case "orange":
         System.out.println("orange");
        
         break;
         case "pomigrant":
            System.out.println("pomigrant");
            break;
            case "papaya":
                System.out.println("papaya");
                break;
   
            default:
         System.out.println("invalid fruits name");
         break;
   }
}
    
}